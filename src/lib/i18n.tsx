export type TranslationKey = keyof typeof translations.ar | (string & {});

interface I18nContextType {
  lang: LanguageCode;
  setLang: (lang: LanguageCode) => void;
  t: (key: TranslationKey, fallback?: string) => string;
  dir: "rtl" | "ltr";
  isRTL: boolean;
  currentLanguage: LanguageOption;
  languages: LanguageOption[];
}

const I18nContext = createContext<I18nContextType | null>(null);

const STORAGE_KEY = "valoriza_language";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LanguageCode>("ar");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as LanguageCode | null;
      if (saved && (saved === "ar" || saved === "en" || saved === "fr" || saved === "es")) {
        setLangState(saved);
      }
    } catch {
      // ignore
    }
  }, []);

  const currentLanguage = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0]!;
  const dir = currentLanguage.dir;
  const isRTL = dir === "rtl";

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = dir;
    }
  }, [lang, dir]);

  const setLang = (newLang: LanguageCode) => {
    setLangState(newLang);
    try {
      localStorage.setItem(STORAGE_KEY, newLang);
    } catch {
      // ignore
    }
  };

  const t = (key: TranslationKey, fallback?: string): string => {
    const langDict = translations[lang] as Record<string, string> | undefined;
    if (langDict && langDict[key]) {
      return langDict[key]!;
    }
    const fallbackDict = translations.ar as Record<string, string>;
    return fallbackDict[key] || fallback || key;
  };

  return (
    <I18nContext.Provider
      value={{
        lang,
        setLang,
        t,
        dir,
        isRTL,
        currentLanguage,
        languages: LANGUAGES,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    // Graceful fallback if called outside provider
    const fallbackT = (key: TranslationKey, fallback?: string) =>
      translations.ar[key] || fallback || key;
    return {
      lang: "ar" as LanguageCode,
      setLang: () => {},
      t: fallbackT,
      dir: "rtl" as const,
      isRTL: true,
      currentLanguage: LANGUAGES[0]!,
      languages: LANGUAGES,
    };
  }
  return ctx;
}
